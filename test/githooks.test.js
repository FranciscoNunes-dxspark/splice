// Git hooks: what's active and what manages it (pure), then through the UI against a throwaway repository:
// /hooks, a hook's script, running one now (nothing waits on input), and committing and pushing with the
// hooks run or skipped this once.
import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { chmodSync, existsSync, mkdirSync, mkdtempSync, readFileSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import React from 'react';
import { render } from 'ink-testing-library';
import { removeTemp } from './temp.js';
import { frameworkIn, hasHook, hookArgs, hookRows, hookRunArgs, isHuskyRunner, lefthookHooks, preCommitHooks } from '../src/githooks.js';
import { findRepo, readHooks } from '../src/repo.js';
import { App } from '../src/ui/App.jsx';

test('frameworks, their hooks, and how a hook is run by hand', () => {
  assert.equal(frameworkIn('#!/usr/bin/env sh\n. "$(dirname -- "$0")/_/husky.sh"'), 'husky');
  assert.equal(frameworkIn('#!/bin/sh\ncall_lefthook run "pre-commit" "$@"'), 'lefthook');
  assert.equal(frameworkIn('#!/usr/bin/env bash\n# File generated by pre-commit: https://pre-commit.com\nINSTALL_PYTHON=/usr/bin/python3'), 'pre-commit');
  assert.equal(frameworkIn('#!/bin/sh\nnpm test'), null);
  assert.equal(isHuskyRunner('/w/app/.husky/_'), true);
  assert.equal(isHuskyRunner('C:\\w\\app\\.husky\\_\\'), true);
  assert.equal(isHuskyRunner('/w/app/.husky'), false);
  assert.deepEqual(lefthookHooks('pre-commit:\n  commands:\n    lint:\n      run: npm run lint\npre-push:\n  commands: {}\nskip_output:\n  - meta\n'), ['pre-commit', 'pre-push']);
  assert.deepEqual(preCommitHooks('repos: []\n'), ['pre-commit']);
  assert.deepEqual(preCommitHooks('default_install_hook_types: [pre-commit, "commit-msg"]\nrepos: []\n'), ['pre-commit', 'commit-msg']);
  assert.deepEqual(preCommitHooks('default_install_hook_types:\n  - pre-push\n  - nonsense\nrepos: []\n'), ['pre-push']);
  assert.deepEqual(hookArgs('commit-msg', { messageFile: '/r/.git/m' }), ['/r/.git/m']);
  assert.deepEqual(hookArgs('pre-push', { remote: 'origin', url: 'git@x:y.git' }), ['origin', 'git@x:y.git']);
  assert.deepEqual(hookArgs('pre-commit', { remote: 'origin' }), []);
  assert.deepEqual(hookRunArgs('pre-push', '/r/.git/hooks/pre-push', [2, 43, 0], ['origin', 'u']), ['hook', 'run', '--ignore-missing', 'pre-push', '--', 'origin', 'u']);
  assert.deepEqual(hookRunArgs('pre-commit', 'C:\\r\\.git\\hooks\\pre-commit', [2, 30, 0]), ['-c', 'alias.splice-run-hook=!"C:/r/.git/hooks/pre-commit"', 'splice-run-hook']);
  const hooks = { hooks: [{ name: 'pre-commit', shown: '.git/hooks/pre-commit', framework: 'lefthook' }], frameworks: [{ name: 'lefthook', file: 'lefthook.yml', hooks: ['pre-commit', 'pre-push'] }] };
  assert.equal(hasHook(hooks, ['pre-commit', 'commit-msg']), true);
  assert.equal(hasHook(hooks, ['pre-push']), false);
  assert.deepEqual(hookRows(hooks).map((r) => [r.label, r.detail]), [
    ['pre-commit', '.git/hooks/pre-commit  (lefthook)'],
    ['lefthook', 'lefthook.yml: pre-commit, pre-push  · not installed: pre-push (lefthook install)'],
  ]);
});

let base;
let dir;
let origin;
let lastApp = null;
const run = (cwd, ...args) => execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], env: { ...process.env, GIT_OPTIONAL_LOCKS: '0' } }).trim();
const git = (...args) => run(dir, ...args);
const log = () => (existsSync(join(dir, '.git', 'hook-log')) ? readFileSync(join(dir, '.git', 'hook-log'), 'utf8') : '');

const hook = (name, body) => {
  const file = join(dir, '.git', 'hooks', name);
  writeFileSync(file, `#!/bin/sh\n${body}\n`);
  chmodSync(file, 0o755);
};

before(() => {
  base = realpathSync.native(mkdtempSync(join(tmpdir(), 'splice-githooks-')));
  dir = join(base, 'repo');
  origin = join(base, 'origin.git');
  mkdirSync(dir);
  process.env.SPLICE_HOME = join(base, 'home');
  run(base, 'init', '-q', '--bare', '-b', 'main', origin);
  git('init', '-q', '-b', 'main');
  git('config', 'core.autocrlf', 'false');
  git('config', 'user.name', 'Test');
  git('config', 'user.email', 'test@example.com');
  git('config', 'commit.gpgsign', 'false');
  writeFileSync(join(dir, 'a.txt'), 'a\n');
  writeFileSync(join(dir, 'lefthook.yml'), 'pre-commit:\n  commands:\n    lint:\n      run: echo lint\n');
  git('add', '.');
  git('commit', '-q', '-m', 'First commit');
  git('remote', 'add', 'origin', origin);
  git('push', '-q', '-u', 'origin', 'main');
  // A pre-commit hook that says it ran, and reads its input (there is none: it mustn't wait); a pre-push
  // hook that notes its arguments.
  hook('pre-commit', 'read line; echo "pre-commit ran" >> .git/hook-log; echo checked the staged files');
  hook('pre-push', 'echo "pre-push $1" >> .git/hook-log');
  writeFileSync(join(dir, '.git', 'hooks', 'post-commit.sample'), '#!/bin/sh\n');
});

after(() => removeTemp(base));

async function until(check, what, ms = 10000) {
  const end = Date.now() + ms;
  while (Date.now() < end) {
    let ok = false;
    try {
      ok = check();
    } catch {
      // not yet
    }
    if (ok) return new Promise((r) => setTimeout(r, 100));
    await new Promise((r) => setTimeout(r, 40));
  }
  throw new Error(`Timed out waiting for ${what}. Last frame:\n${lastApp?.lastFrame()}`);
}

const type = async (stdin, text) => {
  for (const ch of text) {
    stdin.write(ch);
    await new Promise((r) => setTimeout(r, 5));
  }
};

async function command(app, text) {
  app.stdin.write('/');
  await until(() => app.lastFrame().includes('> /'), 'the prompt');
  await type(app.stdin, text);
  await until(() => app.lastFrame().includes(`> /${text}`), `/${text} typed`);
  app.stdin.write('\r');
}

test('reading the hooks: executable named ones only, and husky 9 by its scripts', async () => {
  const repo = await findRepo(dir);
  const found = await readHooks(repo);
  assert.deepEqual(found.hooks.map((h) => h.name), ['pre-commit', 'pre-push']);
  assert.deepEqual(found.frameworks, [{ name: 'lefthook', file: 'lefthook.yml', hooks: ['pre-commit'] }]);
  // Husky 9: every hook is a runner in .husky/_, but only those with a script in .husky count.
  mkdirSync(join(dir, '.husky', '_'), { recursive: true });
  for (const n of ['pre-commit', 'pre-push']) {
    writeFileSync(join(dir, '.husky', '_', n), '#!/bin/sh\n. "$(dirname "$0")/h"\n');
    chmodSync(join(dir, '.husky', '_', n), 0o755);
  }
  writeFileSync(join(dir, '.husky', 'pre-commit'), 'npm test\n');
  const husky = await readHooks(repo, '.husky/_');
  assert.deepEqual(husky.hooks.map((h) => [h.name, h.shown, h.framework]), [['pre-commit', '.husky/pre-commit', 'husky']]);
  rmSync(join(dir, '.husky'), { recursive: true, force: true });
  if (process.platform !== 'win32') {
    chmodSync(join(dir, '.git', 'hooks', 'pre-push'), 0o644);
    assert.deepEqual((await readHooks(repo)).hooks.map((h) => h.name), ['pre-commit'], 'not executable: git skips it');
    chmodSync(join(dir, '.git', 'hooks', 'pre-push'), 0o755);
  }
});

test('/hooks lists and shows them and runs one; a commit and a push ask whether to run their hooks', async () => {
  lastApp = render(React.createElement(App, { initialPath: dir, config: { recent: [], roots: [], history: [] } }));
  const app = lastApp;
  const frame = () => app.lastFrame() ?? '';
  try {
    await until(() => frame().includes('First commit'), 'the graph');
    await command(app, 'hooks');
    await until(() => frame().includes('Git hooks in .git/hooks') && frame().includes('pre-push'), 'the list');
    // Its pre-commit is installed (a hook is there), so nothing is said to be missing.
    assert.match(frame(), /lefthook\s+lefthook\.yml: pre-commit\s+│/);
    assert.doesNotMatch(frame(), /post-commit/, 'a .sample is not a hook');
    assert.match(frame(), /❯ pre-commit/);
    app.stdin.write('\r');
    await until(() => frame().includes('pre-commit: .git/hooks/pre-commit') && frame().includes('echo "pre-commit ran"'), 'the script');
    app.stdin.write('\x1b');
    await until(() => frame().includes('Git hooks in'), 'back to the list');
    app.stdin.write('r');
    await until(() => frame().includes('pre-commit: passed') && frame().includes('checked the staged files'), 'its output, having run without waiting');
    assert.equal(log(), 'pre-commit ran\n');
    app.stdin.write('\x1b');
    await until(() => frame().includes('Git hooks in'), 'back to the list');
    app.stdin.write('\x1b');
    await until(() => !frame().includes('Git hooks in'), 'closed');

    // Committing: skip the hooks this once, then run them.
    writeFileSync(join(dir, 'a.txt'), 'a\nb\n');
    git('add', 'a.txt');
    await until(() => frame().includes('1 change'), 'the change');
    await command(app, 'commit Skip them');
    await until(() => frame().includes('Commit "Skip them"?') && frame().includes('skip the hooks this once (--no-verify)'), 'the question');
    app.stdin.write('2');
    await until(() => git('log', '-1', '--format=%s') === 'Skip them', 'committed');
    assert.equal(log(), 'pre-commit ran\n', 'the hook skipped');
    writeFileSync(join(dir, 'a.txt'), 'a\nb\nc\n');
    git('add', 'a.txt');
    await until(() => frame().includes('1 change'), 'the next change');
    await command(app, 'commit Run them');
    await until(() => frame().includes('Commit "Run them"?'), 'asked again');
    app.stdin.write('1');
    await until(() => git('log', '-1', '--format=%s') === 'Run them', 'committed again');
    assert.equal(log(), 'pre-commit ran\npre-commit ran\n', 'the hook ran');

    // Pushing: the pre-push hook runs with the remote's name.
    app.stdin.write('P');
    await until(() => frame().includes('Push main?') && frame().includes('running the pre-push hook'), 'the push question');
    app.stdin.write('1');
    await until(() => run(origin, 'rev-parse', 'main') === git('rev-parse', 'HEAD'), 'pushed');
    assert.equal(log(), 'pre-commit ran\npre-commit ran\npre-push origin\n');
  } finally {
    app.unmount();
  }
});
